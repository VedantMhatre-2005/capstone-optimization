# CHART 4: Statistical Significance Matrix (-log10(p) & Cohen's d Effect Size)
# ==============================================================================
def plot_chart4_significance_matrix(stats_4node):
    """Plots heatmap matrix of per-scenario -log10(p-values) and Cohen's d effect sizes."""
    print("[INFO] Generating Statistical Chart 4: Statistical Significance Heatmap...")

    scenarios = [f"S{i+1}: {item['scenario_name'].split('.')[1].strip()}" for i, item in enumerate(stats_4node)]
    
    p_vals = [item["p_value"] for item in stats_4node]
    cohen_ds = [item["cohen_d"] for item in stats_4node]
    t_stats = [item["t_stat"] for item in stats_4node]

    # Convert p-values to -log10(p) for visual scale
    neg_log_p = [-math.log10(p) if p > 0 else 5.0 for p in p_vals]

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 7))

    # Panel A: -log10(p-value)
    y_pos = np.arange(len(scenarios))
    bars1 = ax1.barh(y_pos, neg_log_p, color='#7b1fa2', edgecolor='black', height=0.6)
    ax1.axvline(x=-math.log10(0.05), color='#ff9800', linestyle='--', label='p = 0.05 Threshold')
    ax1.axvline(x=-math.log10(0.001), color='#d32f2f', linestyle=':', label='p = 0.001 High Significance')

    for bar, p in zip(bars1, p_vals):
        w = bar.get_width()
        p_str = "<0.001" if p < 0.001 else f"{p:.3f}"
        ax1.text(w + 0.1, bar.get_y() + bar.get_height()/2.0, f"p={p_str}", va='center', fontsize=9, fontweight='bold')

    ax1.set_yticks(y_pos)
    ax1.set_yticklabels(scenarios, fontsize=9)
    ax1.set_xlabel('Statistical Significance $-\\log_{10}(p\\text{-value})$', fontsize=11, fontweight='bold')
    ax1.set_title('Paired t-test Statistical Significance per Scenario', fontsize=12, fontweight='bold', pad=10)
    ax1.grid(axis='x', linestyle=':', alpha=0.6)
    ax1.legend(loc='lower right', fontsize=9)

    # Panel B: Cohen's d Effect Size
    bars2 = ax2.barh(y_pos, cohen_ds, color='#0288d1', edgecolor='black', height=0.6)
    ax2.axvline(x=0.8, color='#ff9800', linestyle='--', label='Large Effect (d = 0.8)')

    for bar, d in zip(bars2, cohen_ds):
        w = bar.get_width()
        ax2.text(w + 0.1, bar.get_y() + bar.get_height()/2.0, f"d={d:.2f}", va='center', fontsize=9, fontweight='bold')

    ax2.set_yticks(y_pos)
    ax2.set_yticklabels([], fontsize=9)
    ax2.set_xlabel("Cohen's $d$ Effect Size", fontsize=11, fontweight='bold')
    ax2.set_title("Standardized Effect Size (Cohen's d)", fontsize=12, fontweight='bold', pad=10)
    ax2.grid(axis='x', linestyle=':', alpha=0.6)
    ax2.legend(loc='lower right', fontsize=9)

    plt.suptitle("Statistical Rigor Analysis: Paired t-Test Significance & Effect Size per Scenario", fontsize=15, fontweight='bold', y=0.98)
    plt.tight_layout()

    out_path = os.path.join(OUTPUT_DIR, "statistical_significance_pvalues.png")
    plt.savefig(out_path, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"   [SAVED] -> {out_path}")


