"""
generate_statistical_charts.py
================================
Publication-Grade Statistical Visualization Generator with Error Bars & CI Envelopes.

Generates 4 high-resolution (300 DPI) academic graphics:
1. Scenario Peak Reduction with 95% Confidence Interval Error Bars (QAOA vs PSO)
2. Convergence Curves with ±1σ Shaded Confidence Envelopes across Seeds
3. Violin & Boxplot Distribution Comparison (Baseline vs PSO vs QAOA)
4. Statistical Significance Heatmap Matrix (-log10(p) and Cohen's d Effect Size)
"""

import os
import sys
import json
import math
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.cm as cm

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

current_dir = os.path.dirname(os.path.abspath(__file__))
if current_dir not in sys.path:
    sys.path.insert(0, current_dir)

OUTPUT_DIR = os.path.join(current_dir, "charts")
JSON_PATH = os.path.join(OUTPUT_DIR, "statistical_results.json")

plt.rcParams['font.sans-serif'] = 'DejaVu Sans'
plt.rcParams['axes.edgecolor'] = '#cccccc'
plt.rcParams['axes.linewidth'] = 1.0


def load_statistical_data():
    """Loads JSON statistical summary file generated by run_statistical_eval.py."""
    if not os.path.exists(JSON_PATH):
        raise FileNotFoundError(f"Statistical data file not found at {JSON_PATH}. Run run_statistical_eval.py first.")
    with open(JSON_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


# ==============================================================================
# CHART 1: Scenario Peak Reduction % with 95% Confidence Interval Error Bars
# ==============================================================================
def plot_chart1_peak_reduction_ci(stats_4node):
    """Plots QAOA vs PSO peak reduction % with asymmetric 95% CI error bars."""
    print("[INFO] Generating Statistical Chart 1: Peak Reduction with 95% CI Error Bars...")

    scenarios = [f"S{i+1}: {item['scenario_name'].split('.')[1].strip()}" for i, item in enumerate(stats_4node)]
    
    pso_means = [item["pso_red_stats"]["mean"] for item in stats_4node]
    pso_cis = [item["pso_red_stats"]["ci_margin"] for item in stats_4node]

    qaoa_means = [item["qaoa_red_stats"]["mean"] for item in stats_4node]
    qaoa_cis = [item["qaoa_red_stats"]["ci_margin"] for item in stats_4node]

    x = np.arange(len(scenarios))
    width = 0.35

    plt.figure(figsize=(16, 6.5))

    plt.bar(
        x - width/2, pso_means, width, yerr=pso_cis, capsize=4,
        label='Classical PSO (Mean ± 95% CI)', color='#0288d1', edgecolor='black', alpha=0.9,
        error_kw=dict(ecolor='black', lw=1.2, capsize=3, capthick=1.2)
    )
    plt.bar(
        x + width/2, qaoa_means, width, yerr=qaoa_cis, capsize=4,
        label='QAOA Quantum (Mean ± 95% CI)', color='#388e3c', edgecolor='black', alpha=0.9,
        error_kw=dict(ecolor='black', lw=1.2, capsize=3, capthick=1.2)
    )

    # Annotate significance markers (*** p < 0.001)
    for i, item in enumerate(stats_4node):
        p_val = item["p_value"]
        if p_val < 0.001:
            max_y = max(pso_means[i] + pso_cis[i], qaoa_means[i] + qaoa_cis[i])
            plt.text(i, max_y + 1.2, "***", ha='center', va='bottom', fontsize=11, fontweight='bold', color='#d32f2f')

    plt.ylabel('Peak Congestion Reduction (%)', fontsize=11, fontweight='bold')
    plt.xlabel('Traffic Scenario (15 Diverse Real-World Patterns)', fontsize=11, fontweight='bold')
    plt.title('Scenario Congestion Reduction Efficiency with 95% Confidence Intervals (4-Node Network)', fontsize=14, fontweight='bold', pad=12)
    plt.xticks(x, scenarios, rotation=45, ha='right', fontsize=9)
    plt.axhline(y=0, color='black', linewidth=1.0)
    plt.grid(axis='y', linestyle=':', alpha=0.6)
    plt.ylim(min(0, min(pso_means)) - 5, max(qaoa_means + pso_means) + 8)
    plt.legend(loc='upper right', fontsize=10, framealpha=0.95)

    plt.tight_layout()
    out_path = os.path.join(OUTPUT_DIR, "scenario_peak_reduction_with_ci.png")
    plt.savefig(out_path, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"   [SAVED] -> {out_path}")


